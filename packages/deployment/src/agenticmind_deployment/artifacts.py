"""Deployment artifacts per target and profile (ADR-0020).

Artifacts sit next to the compiled app under ``deploy/<target>/`` and reference secrets **by name only**:
Compose passes them through from the environment, Kubernetes reads a Secret, Cloud Run reads Secret
Manager. Values never appear in any generated file.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

import yaml

from .requirements import Requirements

APP_PORT = 8080
API_KEYS = "APP_API_KEYS"


@dataclass
class ArtifactOptions:
    name: str  # app/service name (DNS-safe)
    project_id: str
    revision: int
    profile: str
    image: str = ""  # registry/repo for guided targets; empty → a placeholder the README explains
    env: dict[str, str] | None = None  # non-secret settings

    @property
    def tag(self) -> str:
        return f"rev{self.revision}"


def dns_name(text: str) -> str:
    name = re.sub(r"[^a-z0-9-]+", "-", text.lower()).strip("-")
    return (name or "agenticmind-app")[:50].rstrip("-")


def _dump(doc: Any) -> str:
    return yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=110)


def secret_names(req: Requirements) -> list[str]:
    return sorted({*req.secrets, API_KEYS})


def _replicas(req: Requirements, profile: str) -> int:
    if req.in_process_state or req.persistent_data or profile == "development":
        return 1
    return 2


def _request_timeout(req: Requirements, floor: float, ceiling: float) -> int:
    return int(min(max(req.longest_request_seconds + 30, floor), ceiling))


def _memory(req: Requirements) -> str:
    return f"{max(512, req.memory_mb)}Mi"


# ---- Docker Compose (local + server) ------------------------------------------------------------
def compose(req: Requirements, o: ArtifactOptions, *, local: bool) -> str:
    env: list[str] = [*secret_names(req)]  # names only: values pass through from the environment
    env += [f"{k}={v}" for k, v in sorted((o.env or {}).items())]
    service: dict[str, Any] = {
        "build": {"context": "../.."},
        "image": f"agenticmind/{o.name}:{o.tag}"
        if local
        else "${IMAGE:-agenticmind/" + o.name + "}:${TAG:-" + o.tag + "}",
        "ports": ["127.0.0.1:${AM_HOST_PORT:?set by the deployer}:8080" if local else "${HOST_PORT:-8080}:8080"],
        "environment": env,
        "volumes": ["data:/app/data"],
        "labels": {
            "dev.agenticmind.project": o.project_id,
            "dev.agenticmind.revision": str(o.revision),
            "dev.agenticmind.profile": o.profile,
        },
    }
    if o.profile != "development":
        service["restart"] = "unless-stopped"
        service["read_only"] = True
        service["tmpfs"] = ["/tmp"]
        service["logging"] = {"driver": "json-file", "options": {"max-size": "10m", "max-file": "3"}}
        service["deploy"] = {"resources": {"limits": {"memory": f"{max(512, req.memory_mb)}M"}}}
    doc = {
        "services": {"app": service},
        # one data volume per project, shared by its deployments, so a rollback keeps the index
        "volumes": {"data": {"name": f"am-{dns_name(o.project_id)}-data"}},
    }
    header = (
        "# Generated by the AgenticMind Deployment Center. Secrets are listed by name only; their values come\n"
        "# from the environment of `docker compose` (or an .env file next to it), never from this file.\n"
    )
    return header + _dump(doc)


def compose_readme(req: Requirements, o: ArtifactOptions) -> str:
    secrets = "\n".join(f"{s}=..." for s in secret_names(req))
    return f"""# Deploy to a Docker server

1. Copy this whole folder (the app plus `deploy/`) to the server, e.g. `rsync -a ./ server:/srv/{o.name}/`.
2. Create `/srv/{o.name}/deploy/docker-server/.env` with the secrets (never commit it):

```
{secrets}
```

3. Build and start:

```
cd /srv/{o.name}
docker compose -f deploy/docker-server/compose.yaml up -d --build
curl -fsS http://localhost:8080/healthz
```

4. Put a TLS reverse proxy (Caddy, nginx, Traefik) in front of port 8080 for public access.

**Roll back:** every build is tagged `{o.tag}` style. Keep the previous image and run
`TAG=<previous tag> docker compose -f deploy/docker-server/compose.yaml up -d`.
Data lives in the `am-{dns_name(o.project_id)}-data` volume; back it up with `docker run --rm -v
am-{dns_name(o.project_id)}-data:/d -v $PWD:/b alpine tar czf /b/data.tgz -C /d .`
"""


# ---- Kubernetes ---------------------------------------------------------------------------------
def kubernetes(req: Requirements, o: ArtifactOptions) -> dict[str, str]:
    name = o.name
    labels = {"app.kubernetes.io/name": name, "app.kubernetes.io/part-of": "agenticmind"}
    secret = f"{name}-secrets"
    replicas = _replicas(req, o.profile)
    needs_volume = bool(req.persistent_data)
    image = f"{o.image or 'REGISTRY/' + name}:{o.tag}"
    container: dict[str, Any] = {
        "name": "app",
        "image": image,
        "ports": [{"name": "http", "containerPort": APP_PORT}],
        "env": [
            *({"name": k, "value": v} for k, v in sorted((o.env or {}).items())),
            *({"name": s, "valueFrom": {"secretKeyRef": {"name": secret, "key": s}}} for s in secret_names(req)),
        ],
        "readinessProbe": {"httpGet": {"path": "/healthz", "port": "http"}, "periodSeconds": 10},
        "livenessProbe": {
            "httpGet": {"path": "/healthz", "port": "http"},
            "periodSeconds": 30,
            "initialDelaySeconds": 20,
        },
        "volumeMounts": [{"name": "data", "mountPath": "/app/data"}, {"name": "tmp", "mountPath": "/tmp"}],
        "securityContext": {
            "runAsNonRoot": True,
            "runAsUser": 10001,
            "allowPrivilegeEscalation": False,
            "readOnlyRootFilesystem": o.profile != "development",
            "capabilities": {"drop": ["ALL"]},
        },
    }
    if o.profile != "development":
        container["resources"] = {
            "requests": {"cpu": "250m", "memory": _memory(req)},
            "limits": {"memory": _memory(req)},
        }
    volumes: list[dict[str, Any]] = [
        {"name": "data", "persistentVolumeClaim": {"claimName": f"{name}-data"}}
        if needs_volume
        else {"name": "data", "emptyDir": {}},
        {"name": "tmp", "emptyDir": {}},
    ]
    deployment = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": name, "labels": labels, "annotations": {"agenticmind.dev/revision": str(o.revision)}},
        "spec": {
            "replicas": replicas,
            # a ReadWriteOnce volume can be attached to one pod at a time
            "strategy": {"type": "Recreate"} if needs_volume else {"type": "RollingUpdate"},
            "selector": {"matchLabels": {"app.kubernetes.io/name": name}},
            "template": {
                "metadata": {"labels": labels},
                "spec": {
                    "securityContext": {"fsGroup": 10001},
                    "containers": [container],
                    "volumes": volumes,
                },
            },
        },
    }
    service = {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": name, "labels": labels},
        "spec": {
            "selector": {"app.kubernetes.io/name": name},
            "ports": [{"name": "http", "port": 80, "targetPort": "http"}],
        },
    }
    files = {"deployment.yaml": _dump(deployment), "service.yaml": _dump(service)}
    resources = ["deployment.yaml", "service.yaml"]
    if needs_volume:
        files["pvc.yaml"] = _dump(
            {
                "apiVersion": "v1",
                "kind": "PersistentVolumeClaim",
                "metadata": {"name": f"{name}-data", "labels": labels},
                "spec": {"accessModes": ["ReadWriteOnce"], "resources": {"requests": {"storage": "5Gi"}}},
            }
        )
        resources.append("pvc.yaml")
    if o.profile == "enterprise":
        egress: list[dict[str, Any]] = [{"to": [{"namespaceSelector": {}}], "ports": [{"port": 53, "protocol": "UDP"}]}]
        if req.network_egress:  # model providers, external services: allow HTTPS out, nothing else
            egress.append({"ports": [{"port": 443, "protocol": "TCP"}]})
        files["networkpolicy.yaml"] = _dump(
            {
                "apiVersion": "networking.k8s.io/v1",
                "kind": "NetworkPolicy",
                "metadata": {"name": name, "labels": labels},
                "spec": {
                    "podSelector": {"matchLabels": {"app.kubernetes.io/name": name}},
                    "policyTypes": ["Ingress", "Egress"],
                    "ingress": [{"ports": [{"port": APP_PORT, "protocol": "TCP"}]}],
                    "egress": egress,
                },
            }
        )
        resources.append("networkpolicy.yaml")
    files["kustomization.yaml"] = _dump(
        {"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": resources}
    )
    keys = " ".join(f"--from-literal={s}=..." for s in secret_names(req))
    files["DEPLOY.md"] = f"""# Deploy to Kubernetes

1. Build and push the image (from the app root):

```
docker build -t {image} .
docker push {image}
```

2. Create the Secret (values from your secret manager; never commit them):

```
kubectl create secret generic {secret} {keys}
```

3. Apply: `kubectl apply -k deploy/kubernetes/` then `kubectl rollout status deployment/{name}`.
4. Expose it with your Ingress or Gateway. Raise the controller's read timeout above
   {int(req.longest_request_seconds)} s if requests can take that long.

Replicas: {replicas}{" (pinned: in-process state or a ReadWriteOnce volume)" if replicas == 1 else ""}.

**Roll back:** `kubectl rollout undo deployment/{name}` (or apply the previous revision's manifests).
"""
    return files


# ---- Cloud Run ----------------------------------------------------------------------------------
def cloud_run(req: Requirements, o: ArtifactOptions) -> dict[str, str]:
    name = o.name
    image = f"{o.image or 'REGION-docker.pkg.dev/PROJECT/REPOSITORY/' + name}:{o.tag}"
    annotations = {"autoscaling.knative.dev/maxScale": "1"} if req.in_process_state else {}
    service = {
        "apiVersion": "serving.knative.dev/v1",
        "kind": "Service",
        "metadata": {"name": name, "labels": {"agenticmind-revision": str(o.revision)}},
        "spec": {
            "template": {
                "metadata": {"annotations": annotations} if annotations else {},
                "spec": {
                    "timeoutSeconds": _request_timeout(req, 300, 3600),
                    "containers": [
                        {
                            "image": image,
                            "ports": [{"containerPort": APP_PORT}],
                            "env": [
                                *({"name": k, "value": v} for k, v in sorted((o.env or {}).items())),
                                *(
                                    {"name": s, "valueFrom": {"secretKeyRef": {"name": s, "key": "latest"}}}
                                    for s in secret_names(req)
                                ),
                            ],
                            "resources": {"limits": {"memory": _memory(req), "cpu": "1"}},
                            "startupProbe": {"httpGet": {"path": "/healthz"}, "failureThreshold": 12},
                        }
                    ],
                },
            }
        },
    }
    creates = "\n".join(
        f'printf %s "$VALUE_OF_{s}" | gcloud secrets create {s} --data-file=-' for s in secret_names(req)
    )
    readme = f"""# Deploy to Google Cloud Run

1. Build and push the image with Cloud Build (from the app root):

```
gcloud builds submit --tag {image}
```

2. Create the secrets in Secret Manager (once) and let the service account read them
   (`roles/secretmanager.secretAccessor`):

```
{creates}
```

3. Deploy: `gcloud run services replace deploy/cloud-run/service.yaml --region REGION`
4. Check: `curl -fsS "$(gcloud run services describe {name} --region REGION --format 'value(status.url)')/healthz"`

Request timeout is set to {_request_timeout(req, 300, 3600)} s (Cloud Run allows up to 3600 s).
{"Max instances is pinned to 1 because the graph keeps state in memory." if req.in_process_state else ""}

**Roll back:** `gcloud run services update-traffic {name} --region REGION --to-revisions=PREVIOUS_REVISION=100`.
"""
    return {"service.yaml": _dump(service), "DEPLOY.md": readme}


# ---- plan-only targets --------------------------------------------------------------------------
def plan_only(target_name: str, req: Requirements, o: ArtifactOptions, steps: list[str]) -> dict[str, str]:
    body = "\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1))
    return {
        "PLAN.md": f"""# {target_name}: deployment plan

AgenticMind does not generate {target_name} artifacts yet. This plan lists what the app needs there.

Secrets (by name): {", ".join(secret_names(req))}
Memory: about {req.memory_mb} MB. Longest request: up to {int(req.longest_request_seconds)} s.
Persistent data: {"yes, mount a volume at /app/data" if req.persistent_data else "not needed"}.
Replicas: {_replicas(req, o.profile)}.

{body}
"""
    }


PLAN_STEPS = {
    "aws_ecs": [
        "Push the image (`docker build` from the app root) to Amazon ECR.",
        "Store each secret in AWS Secrets Manager and reference it from the task definition's `secrets`.",
        "Create a Fargate task definition: container port 8080, health check on /healthz, the memory above.",
        "Mount EFS at /app/data if persistent data is needed.",
        "Create an ECS service behind an Application Load Balancer; raise its idle timeout above the longest request.",
    ],
    "azure_container_apps": [
        "Push the image to Azure Container Registry.",
        "Create the Container App with ingress on port 8080; store secrets as Container Apps secrets or Key Vault "
        "references and map them to environment variables.",
        "Mount an Azure Files share at /app/data if persistent data is needed.",
        "Note the 240-second ingress request timeout.",
    ],
    "vercel": [
        "Host the API on Cloud Run, a Docker server or Kubernetes.",
        "Deploy a frontend to Vercel that calls the API with an X-API-Key from a server-side route.",
    ],
}


def generate(target_id: str, target_name: str, req: Requirements, o: ArtifactOptions) -> dict[str, str]:
    """Files under ``deploy/<target>/``, keyed by their path relative to the app root."""
    folder = {"docker_server": "docker-server", "cloud_run": "cloud-run"}.get(target_id, target_id.replace("_", "-"))
    if target_id == "local":
        files = {"compose.yaml": compose(req, o, local=True)}
    elif target_id == "docker_server":
        files = {"compose.yaml": compose(req, o, local=False), "DEPLOY.md": compose_readme(req, o)}
    elif target_id == "kubernetes":
        files = kubernetes(req, o)
    elif target_id == "cloud_run":
        files = cloud_run(req, o)
    else:
        files = plan_only(target_name, req, o, PLAN_STEPS.get(target_id, []))
    return {f"deploy/{folder}/{path}": text for path, text in files.items()}

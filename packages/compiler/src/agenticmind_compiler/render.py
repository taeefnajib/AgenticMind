# ---- app/api/models.py --------------------------------------------------------------------------
def models_py(endpoints: list[Endpoint]) -> str:
    out: list[str] = []
    for ep in endpoints:
        name = camel(ep.name)
        out += ["", "", f"class {name}Request(BaseModel):", f'    """Input for {ep.path}."""', ""]
        out.append('    model_config = ConfigDict(extra="forbid", populate_by_name=True)')
        if ep.request:
            out.append("")
        for f in ep.request:
            attr, aliased = _field_name(f.key)
            py = REQUEST_TYPES.get(f.value_type, "JsonValue")
            args = [f"alias={_q(f.key)}"] if aliased else []
            if f.required:
                out.append(f"    {attr}: {py} = Field({', '.join(args)})" if args else f"    {attr}: {py}")
            else:
                default = py_literal(f.default) if f.default is not None else "None"
                typ = py if f.default is not None or py == "JsonValue" else f"{py} | None"
                if args:
                    out.append(f"    {attr}: {typ} = Field(default={default}, {', '.join(args)})")
                else:
                    out.append(f"    {attr}: {typ} = {default}")
        out += ["", "", f"class {name}Outputs(BaseModel):", "    model_config = ConfigDict(populate_by_name=True)", ""]
        for r in ep.response:
            attr, aliased = _field_name(r.key)
            py = RESPONSE_TYPES.get(r.port_type, "JsonValue")
            alias = f"Field(default=None, alias={_q(r.key)})" if aliased else "None"
            out.append(f"    {attr}: {py} = {alias}")
        out += [
            "",
            "",
            f"class {name}Response(BaseModel):",
            "    run_id: str",
            "    duration_ms: float",
            f"    outputs: {name}Outputs",
        ]
    body = "\n".join(out)
    names = ["BaseModel", "ConfigDict"] + [n for n in ("Field", "JsonValue") if n in body]
    head = [
        '"""Request and response models, generated from the graph\'s Manual Input and Output nodes."""',
        "",
        "from __future__ import annotations",
        "",
        f"from pydantic import {', '.join(names)}",
    ]
    return "\n".join(head + out) + "\n"



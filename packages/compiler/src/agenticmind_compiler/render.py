def _q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def py_literal(value: Any) -> str:
    """A JSON value as a Python literal in ruff's style (double quotes)."""
    if isinstance(value, bool) or value is None:
        return repr(value)
    if isinstance(value, str):
        return _q(value)
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(py_literal(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{_q(str(k))}: {py_literal(v)}" for k, v in value.items()) + "}"
    raise TypeError(type(value).__name__)


def _field_name(key: str) -> tuple[str, bool]:
    """Python attribute for a JSON key; True when an alias is needed (keywords, BaseModel names)."""
    if keyword.iskeyword(key) or key in _BASEMODEL_NAMES or key.startswith("model_"):
        return f"{key}_", True
    return key, False


def header(project: str, compiler_version: str) -> str:
    return f'"""{project}: generated by the AgenticMind compiler {compiler_version}."""\n'



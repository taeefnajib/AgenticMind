def openapi(title: str, description: str, version: str, endpoints: list[Endpoint], schemas: dict[str, Any]) -> dict:
    paths: dict[str, Any] = {}
    for ep in endpoints:
        op: dict[str, Any] = {
            "summary": ep.summary,
            "operationId": f"{ep.name}_endpoint",
            "tags": ["graph"],
            "requestBody": {
                "required": True,
                "content": {"application/json": {"schema": schemas[ep.name]["request"]}},
            },
            "responses": {
                "200": {
                    "description": "The run succeeded",
                    "content": {"application/json": {"schema": schemas[ep.name]["response"]}},
                },
                "401": {"description": "Missing or invalid X-API-Key"},
                "409": {"description": "The graph paused for human input (not supported in this export)"},
                "422": {"description": "Invalid request"},
                "429": {"description": "Rate limit exceeded"},
                "500": {"description": "A node failed"},
                "502": {"description": "A model or service provider failed"},
            },
        }
        if ep.auth == "api_key":
            op["security"] = [{"ApiKey": []}]
        paths[ep.path] = {"post": op}
    return {
        "openapi": "3.1.0",
        "info": {"title": title, "description": description, "version": version},
        "paths": paths,
        "components": {"securitySchemes": {"ApiKey": {"type": "apiKey", "in": "header", "name": "X-API-Key"}}},
    }

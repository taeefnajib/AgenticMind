SECURITY = '''"""API key authentication and a simple per-client rate limit (in memory, per process)."""

from __future__ import annotations

import hmac
import time
from collections import defaultdict, deque
from collections.abc import Callable

from fastapi import Header, HTTPException, Request


def require_api_key(request: Request, x_api_key: str | None = Header(default=None)) -> None:
    keys = request.app.state.settings.api_keys
    if not keys:
        raise HTTPException(503, "No API keys configured: set APP_API_KEYS on the server")
    if not x_api_key or not any(hmac.compare_digest(x_api_key, k) for k in keys):
        raise HTTPException(401, "Missing or invalid X-API-Key header", headers={"WWW-Authenticate": "ApiKey"})


_hits: dict[tuple[str, str], deque[float]] = defaultdict(deque)


def rate_limit(name: str, per_minute: int) -> Callable[[Request], None]:
    def check(request: Request) -> None:
        if per_minute <= 0:
            return
        client = request.headers.get("x-api-key") or (request.client.host if request.client else "?")
        window = _hits[(name, client)]
        now = time.monotonic()
        while window and now - window[0] > 60:
            window.popleft()
        if len(window) >= per_minute:
            raise HTTPException(429, "Rate limit exceeded", headers={"Retry-After": "60"})
        window.append(now)

    return check
'''


# ---- app/api/routes.py --------------------------------------------------------------------------
def _signature(func: str, model: str) -> list[str]:
    """Endpoint signature laid out the way ruff formats it at line length 120."""
    args = f"body: {model}Request, runtime: GraphRuntime = Depends(get_runtime)"
    one_line = f"async def {func}_endpoint({args}) -> {model}Response:"
    if len(one_line) <= 120:
        return [one_line]
    return [f"async def {func}_endpoint(", f"    {args}", f") -> {model}Response:"]


def routes_py(endpoints: list[Endpoint]) -> str:
    names = sorted(f"{camel(ep.name)}{suffix}" for ep in endpoints for suffix in ("Outputs", "Request", "Response"))
    model_import = "from .models import (\n" + "".join(f"    {n},\n" for n in names) + ")"
    out = [
        '"""HTTP endpoints. Each one runs the part of the graph its outputs depend on."""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Any",
        "",
        "from agenticmind_runtime import RunResult",
        "from fastapi import APIRouter, Depends, HTTPException, Request",
        "",
        "from ..runtime import GraphRuntime, RunFailed, RunWaiting",
        model_import,
        "from .security import rate_limit, require_api_key",
        "",
        "router = APIRouter()",
        "ERRORS: dict[int | str, dict[str, Any]] = {",
        '    401: {"description": "Missing or invalid X-API-Key"},',
        '    409: {"description": "The graph paused for human input (not supported in this export)"},',
        '    429: {"description": "Rate limit exceeded"},',
        '    500: {"description": "A node failed; detail has code, message and node_id"},',
        '    502: {"description": "A model or service provider failed"},',
        "}",
        "",
        "",
        "def get_runtime(request: Request) -> GraphRuntime:",
        "    return request.app.state.runtime",
        "",
        "",
        "async def execute(runtime: GraphRuntime, endpoint: str, payload: dict[str, Any]) -> RunResult:",
        "    try:",
        "        return await runtime.run(endpoint, payload)",
        "    except RunWaiting as exc:",
        '        raise HTTPException(409, "This graph needs a human response; run it in AgenticMind") from exc',
        "    except RunFailed as exc:",
        '        status = 502 if exc.code.startswith(("PROVIDER_", "MODEL_")) else 500',
        '        detail = {"code": exc.code, "message": exc.message, "node_id": exc.node_id}',
        "        raise HTTPException(status, detail) from exc",
    ]
    for ep in endpoints:
        name = camel(ep.name)
        deps = [f"Depends(rate_limit({_q(ep.name)}, {ep.rate_limit_per_minute}))"]
        if ep.auth == "api_key":
            deps.insert(0, "Depends(require_api_key)")
        out += [
            "",
            "",
            "@router.post(",
            f"    {_q(ep.path)},",
            f"    response_model={name}Response,",
            f"    summary={_q(ep.summary)},",
            '    tags=["graph"],',
            "    responses=ERRORS,",
            f"    dependencies=[{', '.join(deps)}],",
            ")",
            *_signature(ep.name, name),
            "    payload = body.model_dump(by_alias=True, exclude_unset=True)",
            f"    result = await execute(runtime, {_q(ep.name)}, payload)",
            "    duration = (result.finished_at - result.started_at).total_seconds() * 1000",
            f"    outputs = {name}Outputs.model_validate(result.outputs)",
            f"    return {name}Response(run_id=result.run_id, duration_ms=duration, outputs=outputs)",
        ]
    return "\n".join(out) + "\n"


